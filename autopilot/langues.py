def langue_de(code: Optional[str]) -> str:
    """Code de langue normalisé (« en-US » -> « en ») ; le français si inconnu ou absent."""
    c = (code or "fr").lower().split("-")[0]
    return c if c in LANGUES else "fr"


def infos(code: Optional[str]) -> dict:
    return LANGUES[langue_de(code)]


def libelle(code: Optional[str], cle: str) -> str:
    return infos(code)["libelles"][cle]


def motifs_interdits(code: Optional[str]):
    """(promesse de gain, avertissement parlé) compilés pour cette langue, ou (None, None) pour le français (qui garde ses contrôles historiques)."""
    d = infos(code)
    if langue_de(code) == "fr":
        return None, None
    return re.compile(d["promesse"], re.I), re.compile(d["avertissement"], re.I)


def mots_vides(code: Optional[str]) -> set[str]:
    return set(infos(code)["vides"].split())


# ---------------------------------------------------------------- reconnaissance grossière de la langue (garde-fou, pas un détecteur)
def _mots(t: str) -> list[str]:
    return re.findall(r"[a-zà-ÿœ']+", (t or "").lower())


def part_de_langue(texte: str, code: str) -> float:
    """Part des mots du texte qui sont des mots vides de la langue `code` (0 à 1)."""
    m = _mots(texte)
    if not m:
        return 0.0
    v = mots_vides(code)
    return sum(1 for w in m if w in v) / len(m)


def langue_plausible(texte: str, code: str) -> bool:
    """Vrai si le texte ressemble plus à `code` qu'à toute autre langue connue (sert à refuser un « texte traduit » resté dans la langue source)."""
    c = langue_de(code)
    mine = part_de_langue(texte, c)
    if mine < 0.12:
        return False
    return all(mine >= part_de_langue(texte, autre) for autre in LANGUES if autre != c)


# ---------------------------------------------------------------- chiffres -> lettres (anglais)
_UNITES = ("zero one two three four five six seven eight nine ten eleven twelve thirteen fourteen fifteen sixteen seventeen eighteen nineteen").split()
_DIZ = "_ _ twenty thirty forty fifty sixty seventy eighty ninety".split()
_ECHELLES = [(10 ** 12, "trillion"), (10 ** 9, "billion"), (10 ** 6, "million"), (1000, "thousand")]


def entier_en_lettres(n: int) -> str:
    """12500 -> « twelve thousand five hundred »."""
    if n < 0:
        return "minus " + entier_en_lettres(-n)
    if n < 20:
        return _UNITES[n]
    if n < 100:
        return _DIZ[n // 10] + ("-" + _UNITES[n % 10] if n % 10 else "")
    if n < 1000:
        return _UNITES[n // 100] + " hundred" + (" " + entier_en_lettres(n % 100) if n % 100 else "")
    for valeur, nom in _ECHELLES:
        if n >= valeur:
            reste = n % valeur
            return entier_en_lettres(n // valeur) + " " + nom + (" " + entier_en_lettres(reste) if reste else "")
    return str(n)  # inatteignable


def annee_en_lettres(n: int) -> str:
    """Année prononcée : 2014 -> « twenty fourteen », 1905 -> « nineteen oh five », 2000 -> « two thousand »."""
    if n % 1000 == 0:
        return entier_en_lettres(n)
    if 2000 < n < 2010:
        return "two thousand " + _UNITES[n - 2000]
    haut, bas = divmod(n, 100)
    if bas == 0:
        return entier_en_lettres(haut) + " hundred"
    if bas < 10:
        return entier_en_lettres(haut) + " oh " + _UNITES[bas]
    return entier_en_lettres(haut) + " " + entier_en_lettres(bas)


_DEVISES = {"$": ("dollar", "dollars", "cent", "cents"), "€": ("euro", "euros", "cent", "cents"), "£": ("pound", "pounds", "penny", "pence")}
_RE_NOMBRE = re.compile(r"(?<![\w.,])(?:(?P<dev>[$€£])\s?)?(?P<n>\d{1,3}(?:,\d{3})+|\d+)(?:\.(?P<d>\d+))?(?P<suf>\s?%|\s?(?:k|K)\b|\s?(?:[$€£])|\s?(?:dollars?|euros?))?")
_RE_ANNEE_CTX = re.compile(r"(?:in|since|by|until|before|after|during|from|of|year|circa|around)\s*$", re.I)


def chiffres_en_lettres_en(texte: str) -> str:
    """Remplace tout chiffre d'un texte parlé anglais par des mots : « $12,500 » -> « twelve thousand five hundred dollars », « 5% » -> « five percent »,
    « in 2014 » -> « in twenty fourteen », « 2.5 » -> « two point five ». Les valeurs ne changent pas, seule l'écriture."""
    def conv(m: re.Match) -> str:
        n = int(m["n"].replace(",", ""))
        dev, dec, suf = m["dev"], m["d"], (m["suf"] or "").strip()
        avant = texte[: m.start()]
        mot_dev = None
        if dev:
            mot_dev = dev
        elif suf in _DEVISES:
            mot_dev = suf
        elif re.fullmatch(r"dollars?", suf, re.I):
            mot_dev = "$"
        elif re.fullmatch(r"euros?", suf, re.I):
            mot_dev = "€"
        if mot_dev and not dec:
            sing, plur, *_ = _DEVISES[mot_dev]
            return f"{entier_en_lettres(n)} {sing if n == 1 else plur}"
        if mot_dev and dec:
            sing, plur, csing, cplur = _DEVISES[mot_dev]
            cents = int((m["d"] + "0")[:2])
            return f"{entier_en_lettres(n)} {sing if n == 1 else plur} and {entier_en_lettres(cents)} {csing if cents == 1 else cplur}"
        if dec:
            base = entier_en_lettres(n) + " point " + " ".join(_UNITES[int(c)] for c in dec)
        elif 1100 <= n <= 2099 and "," not in m["n"] and _RE_ANNEE_CTX.search(avant) and not suf:
            base = annee_en_lettres(n)
        else:
            base = entier_en_lettres(n)
        if suf == "%":
            return base + " percent"
        if suf.lower() == "k":
            return base + " thousand"
        return base
    return _RE_NOMBRE.sub(conv, texte)


def chiffres_en_lettres(texte: str, code: str) -> str:
    """Chiffres -> lettres pour les langues qui savent le faire (anglais) ; sinon le texte tel quel (le contrôle refusera les chiffres restants)."""
    if langue_de(code) == "en":
        return chiffres_en_lettres_en(texte)
    return texte


def a_des_chiffres(texte: str) -> bool:
    return bool(re.search(r"\d", texte or ""))
